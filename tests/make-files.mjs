function save(name, aoa, merges) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  if (merges && merges.length) ws['!merges'] = merges;
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, '시트1');
  const p = path.join(OUT, name + '.xlsx');
  XLSX.writeFile(wb, p);
  console.log('생성:', name + '.xlsx');
}
